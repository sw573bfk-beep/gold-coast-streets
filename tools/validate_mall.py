"""Check Cavill Mall in the built map against the shop registry.

Run: python3 tools/validate_mall.py   (after build_map.py; writes reports/cavill_mall_report.md)
Exit code 1 if any shop is on the wrong side, out of order, missing, or has an overlapping sign.
"""
import json, math, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
m = json.load(open(os.path.join(ROOT, 'data', 'map.json')))
reg = json.load(open(os.path.join(ROOT, 'data', 'shops_registry.json')))['shops']
mf = m['details']['mall']
MALL = [(mf[i], mf[i + 1]) for i in range(0, len(mf), 2)]
CUM = [0.0]
for i in range(1, len(MALL)):
    CUM.append(CUM[-1] + math.hypot(MALL[i][0] - MALL[i - 1][0], MALL[i][1] - MALL[i - 1][1]))

def proj(x, z):
    best = None
    for i in range(len(MALL) - 1):
        ax, az = MALL[i]; bx, bz = MALL[i + 1]; ex, ez = bx - ax, bz - az; L = math.hypot(ex, ez)
        t = max(0, min(1, ((x - ax) * ex + (z - az) * ez) / (L * L))); cx, cz = ax + ex * t, az + ez * t
        d = math.hypot(x - cx, z - cz); side = 1 if ex * (z - az) - ez * (x - ax) > 0 else -1
        if best is None or d < best[0]: best = (d, CUM[i] + t * L, side)
    return best

signs = {s[13]: s for s in m['details']['signs']}
poles = {s[4]: s for s in m['details']['freeSigns']}
mall = [r for r in reg if r.get('mall')]
problems = []
rows = {-1: [], 1: []}
for r in mall:
    side = r['mall']['side']
    pl = r.get('placement')
    if not pl:
        problems.append(('missing', r, 'no sign placed')); continue
    d, s_game, side_game = proj(pl['x'], pl['z'])
    rows[side].append((r, s_game, side_game, d))
    if side_game != side:
        problems.append(('wrong side', r, 'placed on the %s side' % ('south' if side_game > 0 else 'north')))
    if abs(s_game - r['mall']['s']) > 6:
        problems.append(('displaced', r, 'placed %+.1f m from its source position' % (s_game - r['mall']['s'])))
    if d > 16:
        problems.append(('set back', r, 'sign is %.0f m from the walkway centreline' % d))
for side, row in rows.items():
    ref = sorted(row, key=lambda q: q[0]['mall']['s'])
    for i in range(len(ref) - 1):
        a, b = ref[i], ref[i + 1]
        if a[1] > b[1] + 0.05:
            problems.append(('out of order', b[0], 'appears before %s in game' % a[0]['name']))
# overlapping or coincident signs anywhere along the mall
ms = [(s, proj(s[0], s[1])) for s in m['details']['signs']]
ms = [(s, p) for s, p in ms if p[0] < 20]
for i in range(len(ms)):
    for j in range(i + 1, len(ms)):
        a, pa = ms[i]; b, pb = ms[j]
        if pa[2] != pb[2] or abs(a[5] - b[5]) > 0.5: continue
        if math.hypot(a[0] - b[0], a[1] - b[1]) < (a[4] + b[4]) / 2 - 0.05 and abs(a[2] * b[2] + a[3] * b[3]) > 0.8:
            problems.append(('overlapping signs', next(r for r in reg if r['id'] == a[13]), 'overlaps ' + b[7]))

lines = ['# Cavill Mall check', '', 'Generated by `tools/validate_mall.py` from `data/shops_registry.json` and `data/map.json`.', '',
         'Positions are metres along the mall walkway from Surfers Paradise Blvd (0 m) to The Esplanade (%.0f m).' % CUM[-1], '',
         '**Problems found: %d**' % len(problems), '']
for kind, r, why in problems:
    lines.append('- **%s** — %s (`%s`): %s' % (kind, r['name'], r['id'], why))
for side, title in ((-1, 'North side (Soul, Ripley\'s, Universal Store…)'), (1, 'South side (Paradise Centre frontage, Timezone, Grill\'d…)')):
    lines += ['', '## ' + title, '', '| # | Business | Status | Source position | In game | Shift | Walk-in | Source |', '|---|---|---|---|---|---|---|---|']
    for r, s_game, _, _ in sorted(rows[side], key=lambda q: q[1]):
        src = r['source']
        link = '[%s](%s)' % (src['ref'], src['url']) if src.get('url') else (src.get('ref') or src['kind'])
        lines.append('| %d | %s | %s | %.0f m | %.0f m | %+.1f m | %s | %s |' % (r['mall'].get('order', 0), r['name'], r['status'], r['mall']['s'], s_game,
                                                                          s_game - r['mall']['s'], 'yes' if r['placement']['walkIn'] else 'counter', link))
os.makedirs(os.path.join(ROOT, 'reports'), exist_ok=True)
open(os.path.join(ROOT, 'reports', 'cavill_mall_report.md'), 'w').write('\n'.join(lines) + '\n')
print('mall shops', len(mall), 'north', len(rows[-1]), 'south', len(rows[1]), 'problems', len(problems))
for kind, r, why in problems:
    print(' ', kind, '-', r['name'], '-', why)
sys.exit(1 if any(k in ('wrong side', 'out of order', 'missing', 'overlapping signs') for k, _, _ in problems) else 0)
