"""Summarise data/shops_registry.json into reports/shop_audit.md (counts, merges, removals, approximations)."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
reg = json.load(open(os.path.join(ROOT, 'data', 'shops_registry.json')))['shops']
by = {}
for r in reg: by.setdefault(r['status'], []).append(r)
LABEL = {'verified': '1. Verified real business (OpenStreetMap location + Google Maps listing or player confirmation)',
         'unverified': '5. Unverified listing (OpenStreetMap only; open status not checked)',
         'approximate': '2. Real business, approximate placement (from a street address)',
         'fictional': '3. Fictional business', 'duplicate': '4. Duplicate (not placed separately)', 'obsolete': '4. Obsolete listing (not placed)'}
lines = ['# Shop audit', '', 'Generated by `tools/audit_shops.py` from `data/shops_registry.json` (the source of truth for shop placement).', '',
         '| Classification | Records |', '|---|---|']
for k in ['verified', 'approximate', 'fictional', 'duplicate', 'obsolete', 'unverified']:
    lines.append('| %s | %d |' % (LABEL[k], len(by.get(k, []))))
lines += ['', 'Total records: %d. Placed in the game: %d (%d walk-in, %d served at a counter or sign).' % (
    len(reg), sum(1 for r in reg if r.get('placement')), sum(1 for r in reg if r.get('interaction') == 'walk-in'), sum(1 for r in reg if r.get('interaction') == 'counter'))]
for k, title in (('duplicate', 'Merged duplicates (kept in the registry, not shown twice)'), ('obsolete', 'Removed from the street (kept in the registry)'),
                 ('fictional', 'Fictional businesses'), ('approximate', 'Approximate placements')):
    lines += ['', '## ' + title, '']
    for r in by.get(k, []):
        lines.append('- %s (`%s`)%s' % (r['name'], r['id'], ' — ' + r['note'] if r.get('note') else ''))
lines += ['', '## Shops moved more than 6 m from their source position to fit the facade', '']
for r in reg:
    if (r.get('placementShift') or 0) > 6 or abs((r.get('mall') or {}).get('shift') or 0) > 6:
        lines.append('- %s (`%s`): %.1f m' % (r['name'], r['id'], r.get('placementShift') or abs(r['mall']['shift'])))
os.makedirs(os.path.join(ROOT, 'reports'), exist_ok=True)
open(os.path.join(ROOT, 'reports', 'shop_audit.md'), 'w').write('\n'.join(lines) + '\n')
print({k: len(v) for k, v in by.items()})
